assert len(all_comps) == 157, f"Esperaba 157, tengo {len(all_comps)}"

# Check pairwise distance
too_close = []
for i in range(len(all_comps)):
    ref1, x1, y1 = all_comps[i]
    for j in range(i + 1, len(all_comps)):
        ref2, x2, y2 = all_comps[j]
        d = math.hypot(x1 - x2, y1 - y2)
        if d < 9.5:  # menos de 9.5 mm podria causar solapamiento de pines
            too_close.append((ref1, ref2, d, (x1, y1), (x2, y2)))

if too_close:
    print(f"ALERTA: {len(too_close)} pares demasiado cercanos (<9.5 mm):")
    for r1, r2, d, p1, p2 in too_close:
        print(f"  {r1} y {r2}: dist={d:.2f} mm ({p1} vs {p2})")
else:
    print("VERDE: Cero pares a menos de 9.5 mm. Espaciado excelente!")
